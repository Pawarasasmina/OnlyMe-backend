import { Router } from "express";
import { protect } from "../middleware/authMiddleware.js";
import { authorize } from "../middleware/roleMiddleware.js";
import { requireAdminPermission } from "../middleware/adminPermissionMiddleware.js";
import { actionUnifiedReport, createLegalHold, exportHistory, getAdminUserDetail, getFinancialUser, getModerationPolicy, getOperationsDashboard, getUnifiedReport, holdPayouts, listAppeals, listAuditEvents, listLegalHolds, listUnifiedReports, releaseLegalHold, releasePayouts, reviewAppeal, searchGovernanceTargets, updateModerationPolicy, enforceUser } from "../controllers/adminOperationsController.js";

import { exportContentHistory, exportUserPackage } from "../controllers/adminExportController.js";
import { listMembershipWorlds, getWorldMemberships, adminCancelMembership, adminRefundMembershipPayment } from "../controllers/adminWorldMembershipController.js";
import { adminFinancialMutationLimit } from "../middleware/financialRateLimit.js";

const router = Router();
router.use(protect, authorize("admin"));
router.get("/operations/dashboard", requireAdminPermission("dashboard.view"), getOperationsDashboard);
router.get("/reports", requireAdminPermission("moderation.view"), listUnifiedReports);
router.get("/reports/:model/:id", requireAdminPermission("moderation.view"), getUnifiedReport);
router.post("/reports/:model/:id/action", requireAdminPermission("moderation.manage"), actionUnifiedReport);
router.get("/appeals", requireAdminPermission("moderation.view"), listAppeals);
router.post("/appeals/:id/review", requireAdminPermission("moderation.manage"), reviewAppeal);
router.get("/moderation-policy", requireAdminPermission("moderation.view"), getModerationPolicy);
router.put("/moderation-policy", requireAdminPermission("governance.manage"), updateModerationPolicy);
router.get("/users/:id/investigation", requireAdminPermission("users.view"), getAdminUserDetail);
router.post("/users/:id/enforce", requireAdminPermission("users.manage"), enforceUser);
router.get("/audit-log", requireAdminPermission("governance.view"), listAuditEvents);
router.get("/governance/targets", requireAdminPermission("governance.view"), searchGovernanceTargets);
router.post("/legal-holds", requireAdminPermission("governance.manage"), createLegalHold);
router.get("/legal-holds", requireAdminPermission("governance.view"), listLegalHolds);
router.post("/legal-holds/:id/release", requireAdminPermission("governance.manage"), releaseLegalHold);
router.get("/exports/history", requireAdminPermission("exports.manage"), exportHistory);
router.get("/exports/content", requireAdminPermission("exports.manage"), exportContentHistory);
router.get("/exports/user-package", requireAdminPermission("exports.manage"), exportUserPackage);
router.get("/finance/users/:id", requireAdminPermission("finance.view"), getFinancialUser);
router.post("/finance/users/:id/payout-hold", requireAdminPermission("finance.manage"), holdPayouts);
router.post("/finance/users/:id/payout-release", requireAdminPermission("finance.manage"), releasePayouts);
router.get("/world-memberships/worlds", requireAdminPermission("finance.view"), listMembershipWorlds);
router.get("/world-memberships/worlds/:worldId", requireAdminPermission("finance.view"), getWorldMemberships);
router.post("/world-memberships/:id/cancel", adminFinancialMutationLimit, requireAdminPermission("finance.manage"), adminCancelMembership);
router.post("/world-memberships/payments/:id/refund", adminFinancialMutationLimit, requireAdminPermission("finance.manage"), adminRefundMembershipPayment);
export default router;
