import { Router } from "express";
import { approveVerifiedCreator, listVerifiedCreatorApplications, rejectVerifiedCreator, updateVerifiedCreatorPrice } from "../controllers/verifiedCreatorController.js";
import { protect } from "../middleware/authMiddleware.js";
import { authorize } from "../middleware/roleMiddleware.js";
import { requireAdminPermission } from "../middleware/adminPermissionMiddleware.js";
const router = Router();
router.use(protect, authorize("admin"));
router.get("/", requireAdminPermission("verification.view"), listVerifiedCreatorApplications);
router.put("/plan", requireAdminPermission("verification.manage"), updateVerifiedCreatorPrice);
router.post("/:id/approve", requireAdminPermission("verification.manage"), approveVerifiedCreator);
router.post("/:id/reject", requireAdminPermission("verification.manage"), rejectVerifiedCreator);
export default router;
