import test from "node:test";
import assert from "node:assert/strict";
import crypto from "node:crypto";
import express from "express";
import mongoose from "mongoose";
import jwt from "jsonwebtoken";
import { MongoMemoryServer } from "mongodb-memory-server";
import User from "../models/User.js";
import CreatorVerification from "../models/CreatorVerification.js";
import PayoutBankApplication from "../models/PayoutBankApplication.js";
import routes from "../routes/manualBankRoutes.js";
import { env } from "../config/env.js";
import { manualPayoutIdentityStatus, decryptBankDetails } from "./manualBankService.js";

test("bank submissions are private, encrypted and ready only after independent admin review", { timeout: 180000 }, async () => {
  const database = await MongoMemoryServer.create();
  const oldKey = process.env.BANK_DETAILS_ENCRYPTION_KEY;
  const oldStripe = process.env.STRIPE_SECRET_KEY;
  process.env.BANK_DETAILS_ENCRYPTION_KEY = crypto.randomBytes(32).toString("hex");
  delete process.env.STRIPE_SECRET_KEY;
  let server;
  try {
    await mongoose.connect(database.getUri());
    await PayoutBankApplication.init();
    const make = (name, role = "fan") => User.create({ name, username: name.toLowerCase(), email: `${name}@example.test`, password: "Password123", role });
    const owner = await make("BankOwner"), other = await make("Other"), admin = await make("BankAdmin", "admin");
    const app = express(); app.use(express.json()); app.use("/", routes); app.use((error, _req, res, _next) => res.status(error.statusCode || 500).json({ message: error.message }));
    server = app.listen(0, "127.0.0.1"); await new Promise(resolve => server.once("listening", resolve));
    const origin = `http://127.0.0.1:${server.address().port}`;
    const request = async (path, user, method = "GET", payload) => {
      const response = await fetch(origin + path, { method, headers: { Authorization: `Bearer ${jwt.sign({ sub: String(user._id) }, env.accessSecret)}`, "Content-Type": "application/json" }, ...(payload && { body: JSON.stringify(payload) }) });
      return { status: response.status, body: await response.json() };
    };
    const details = { accountHolder: "BankOwner", bankName: "Test bank", country: "UAE", currency: "AED", accountNumber: "AE070331234567890123456", swift: "EBILAEAD", routing: "", confirmOwnership: true, version: 0, status: "APPROVED" };
    assert.equal((await request("/bank", owner, "POST", details)).status, 403);
    await CreatorVerification.collection.insertOne({ creator: owner._id, purpose: "IDENTITY", status: "APPROVED", stateSyncPending: false });
    const submitted = await request("/bank", owner, "POST", details);
    assert.equal(submitted.status, 200);
    let bank = submitted.body.data.bank;
    assert.equal(bank.status, "PENDING_REVIEW");
    assert.equal(bank.country, "AE");
    assert.equal(JSON.stringify(submitted.body).includes(details.accountNumber), false);
    const raw = await PayoutBankApplication.collection.findOne({ user: owner._id });
    assert.equal(raw.encryptedDetails.includes(details.accountNumber), false);
    assert.equal(decryptBankDetails(raw.encryptedDetails).accountNumber, details.accountNumber);
    assert.equal((await manualPayoutIdentityStatus(owner)).bankReady, false);
    assert.equal((await request("/bank", owner, "POST", details)).status, 409);
    assert.equal((await request("/bank", other)).body.data.bank, null);
    assert.equal((await request("/admin/banks", other)).status, 403);
    assert.equal((await request(`/admin/banks/${bank.id}`, other)).status, 403);
    assert.equal((await request(`/admin/banks/${bank.id}/review`, other, "POST", { status: "APPROVED", version: bank.version, reviewConfirmed: true })).status, 403);
    const list = await request("/admin/banks", admin);
    assert.equal(JSON.stringify(list.body).includes(details.accountNumber), false);
    const full = await request(`/admin/banks/${bank.id}`, admin);
    assert.equal(full.body.data.bank.accountNumber, details.accountNumber);
    assert.equal((await PayoutBankApplication.findById(bank.id)).history.some(row => row.action === "DETAILS_VIEWED"), true);
    assert.equal((await request(`/admin/banks/${bank.id}/review`, admin, "POST", { status: "APPROVED", version: bank.version })).status, 400);
    let review = await request(`/admin/banks/${bank.id}/review`, admin, "POST", { status: "APPROVED", version: bank.version, reviewConfirmed: true });
    assert.equal(review.status, 200);
    assert.equal((await manualPayoutIdentityStatus(owner)).bankReady, true);
    assert.equal((await manualPayoutIdentityStatus(owner)).bankLast4, "3456");
    assert.equal((await request(`/admin/banks/${bank.id}/review`, admin, "POST", { status: "REJECTED", version: bank.version, reviewConfirmed: true, message: "Stale review" })).status, 409);
    bank = review.body.data.bank;
    const changed = await request("/bank", owner, "POST", { ...details, version: bank.version, accountNumber: "AE070331234567890111111" });
    assert.equal(changed.status, 200);
    assert.equal((await manualPayoutIdentityStatus(owner)).bankReady, false);
    bank = changed.body.data.bank;
    review = await request(`/admin/banks/${bank.id}/review`, admin, "POST", { status: "CHANGES_REQUESTED", version: bank.version, reviewConfirmed: true, message: "Please correct the account number" });
    assert.equal(review.status, 200);
    bank = review.body.data.bank;
    assert.equal((await request("/bank", owner)).body.data.bank.reviewMessage, "Please correct the account number");
    assert.equal((await request("/bank", owner, "POST", { ...details, version: bank.version })).status, 200);
    await CreatorVerification.collection.insertOne({ creator: admin._id, purpose: "IDENTITY", status: "APPROVED", stateSyncPending: false });
    const ownAdminBank = await request("/bank", admin, "POST", details);
    assert.equal((await request(`/admin/banks/${ownAdminBank.body.data.bank.id}/review`, admin, "POST", { status: "APPROVED", version: 1, reviewConfirmed: true })).status, 403);
  } finally {
    if (server) await new Promise(resolve => server.close(resolve));
    await mongoose.disconnect(); await database.stop();
    if (oldKey) process.env.BANK_DETAILS_ENCRYPTION_KEY = oldKey; else delete process.env.BANK_DETAILS_ENCRYPTION_KEY;
    if (oldStripe) process.env.STRIPE_SECRET_KEY = oldStripe;
  }
});
