import test from "node:test";
import assert from "node:assert/strict";
import express from "express";
import { createServer } from "node:http";
import { once } from "node:events";
import mongoose from "mongoose";
import jwt from "jsonwebtoken";
import { Server } from "socket.io";
import { io as connectSocket } from "socket.io-client";
import { MongoMemoryServer } from "mongodb-memory-server";
import User from "../models/User.js";
import Message from "../models/Message.js";
import Conversation from "../models/Conversation.js";
import GroupConversation from "../models/GroupConversation.js";
import GroupMessage from "../models/GroupMessage.js";
import ProfileRelationship from "../models/ProfileRelationship.js";
import UserBlock from "../models/UserBlock.js";
import Story from "../models/Story.js";
import { env } from "../config/env.js";
import { configureMessagingSocket } from "../realtime/messagingSocket.js";
import { getMyPrivacySettings, updateMyPrivacySettings } from "../controllers/profileController.js";
import { listMessages } from "../controllers/messageController.js";
import { getGroupMessages } from "../controllers/groupMessageController.js";
import { getStoryInsights } from "../controllers/storyController.js";
import { sendResponse } from "../utils/response.js";
import presenceRoutes from "../routes/presenceRoutes.js";
import { manualPresenceReset, ownPresence, pauseIdleAtSeen, presenceForViewer, touchPresence } from "./presenceService.js";

test("presence and mutual receipts are private across database, HTTP and sockets", { skip: process.env.PRESENCE_INTEGRATION !== "1", timeout: 90000 }, async t => {
  const database = await MongoMemoryServer.create({ binary: { version: "8.2.6" } });
  const sockets = [];
  let server, io;
  try {
    await mongoose.connect(database.getUri());
    const createUser = name => User.create({ name, username: name.toLowerCase(), email: `${name}@example.test`, password: "Password123!", status: "active" });
    const [alice, bob, carol] = await Promise.all([createUser("Alice"), createUser("Bob"), createUser("Carol")]);
    const app = express(); app.use(express.json());
    app.use(async (req, _res, next) => { try { req.user = await User.findById(req.headers["x-user"]); next(); } catch (error) { next(error); } });
    app.get("/privacy", getMyPrivacySettings); app.put("/privacy", updateMyPrivacySettings);
    app.use("/presence", presenceRoutes);
    app.get("/thread/:userId", listMessages); app.get("/group/:groupId", getGroupMessages);
    app.get("/insights/:id", getStoryInsights);
    app.get("/me", (req, res) => sendResponse(res, 200, "Account", { user: req.user, nested: { lastSeenAt: new Date(), lastActiveAt: new Date() } }));
    app.use((error, _req, res, _next) => res.status(error.statusCode || 500).json({ message: error.message }));
    server = createServer(app); io = new Server(server); app.set("io", io); configureMessagingSocket(io);
    server.listen(0, "127.0.0.1"); await once(server, "listening");
    const base = `http://127.0.0.1:${server.address().port}`;
    const request = async (user, path, body) => {
      const response = await fetch(base + path, { method: body ? path.startsWith("/presence") ? "POST" : "PUT" : "GET", headers: { "x-user": String(user._id), authorization: `Bearer ${jwt.sign({ sub: String(user._id) }, env.accessSecret)}`, "content-type": "application/json" }, ...(body ? { body: JSON.stringify(body) } : {}) });
      return { status: response.status, body: await response.json() };
    };
    const initial = await request(alice, "/privacy");
    assert.equal(initial.body.data.privacySettings.activityStatus, true);
    assert.equal(initial.body.data.privacySettings.readReceipts, true);
    assert.equal((await request(alice, "/privacy", { privacySettings: { activityStatus: "false" } })).status, 400);
    await touchPresence(bob._id, { foreground: true, interaction: true });
    assert.equal((await presenceForViewer(alice._id, [bob._id]))[0].active_now, false);
    await ProfileRelationship.create([{ actor: alice._id, target: bob._id, type: "FOLLOW" }, { actor: bob._id, target: alice._id, type: "FOLLOW" }]);
    assert.equal((await presenceForViewer(alice._id, [bob._id]))[0].active_now, true);
    assert.equal((await presenceForViewer(alice._id, [bob._id], new Date(Date.now() + 120001)))[0].active_now, false, "Presence expires without foreground heartbeats");
    assert.equal((await presenceForViewer(carol._id, [bob._id]))[0].active_now, false);
    const captured = [];
    const socket = connectSocket(base, { auth: { token: jwt.sign({ sub: String(alice._id) }, env.accessSecret) }, transports: ["websocket"], reconnection: false });
    sockets.push(socket); socket.onAny((event, payload) => captured.push({ event, payload }));
    await once(socket, "connect");
    const query = ids => new Promise(resolve => socket.emit("presence:query", ids.map(String), resolve));
    assert.equal((await query([bob._id]))[0].active_now, true);
    await request(alice, "/privacy", { privacySettings: { activityStatus: false, readReceipts: false } });
    assert.equal((await query([bob._id]))[0].active_now, false);
    assert.equal((await presenceForViewer(bob._id, [alice._id]))[0].active_now, false);
    await request(alice, "/privacy", { privacySettings: { activityStatus: true } });
    await request(bob, "/privacy", { privacySettings: { activityStatus: false } });
    assert.equal((await query([bob._id]))[0].active_now, false);
    await request(bob, "/privacy", { privacySettings: { activityStatus: true } });
    await UserBlock.create({ blocker: bob._id, blocked: alice._id });
    assert.equal((await query([bob._id]))[0].active_now, false);
    await UserBlock.deleteMany({});
    await Conversation.create({ fan: alice._id, creator: bob._id, participants: [alice._id, bob._id], status: "ACTIVE" });
    await Message.create({ sender: alice._id, recipient: bob._id, body: "Private receipt", readAt: new Date(), deliveredAt: new Date() });
    let thread = await request(alice, `/thread/${bob._id}`);
    assert.equal(thread.status, 200, JSON.stringify(thread.body));
    assert.equal(thread.body.data.messages[0].readAt, null);
    assert.equal(thread.body.data.messages[0].delivered, true);
    await request(alice, "/privacy", { privacySettings: { readReceipts: true } });
    await request(bob, "/privacy", { privacySettings: { readReceipts: false } });
    assert.equal((await request(alice, `/thread/${bob._id}`)).body.data.messages[0].readAt, null);
    await request(bob, "/privacy", { privacySettings: { readReceipts: true } });
    assert.equal((await request(alice, `/thread/${bob._id}`)).body.data.messages[0].readAt, true);
    const group = await GroupConversation.create({ name: "Circle", createdBy: alice._id, admins: [alice._id], members: [alice._id, bob._id] });
    await GroupMessage.create({ group: group._id, sender: alice._id, body: "Group receipt", readBy: [{ user: bob._id, readAt: new Date() }], deliveredBy: [{ user: bob._id, deliveredAt: new Date() }] });
    await request(bob, "/privacy", { privacySettings: { readReceipts: false } });
    const hiddenGroup = await request(alice, `/group/${group._id}`);
    assert.equal(hiddenGroup.status, 200, JSON.stringify(hiddenGroup.body));
    assert.deepEqual(hiddenGroup.body.data.messages[0].readBy, []);
    assert.equal(hiddenGroup.body.data.messages[0].deliveredBy[0].delivered, true);
    await GroupMessage.updateMany({ group: group._id }, { $set: { readBy: [], deliveredBy: [] } });
    const receiptEvent = once(socket, "group:receipt");
    await request(bob, `/group/${group._id}`);
    await receiptEvent;
    const receipts = captured.filter(row => row.event === "group:receipt");
    assert.ok(receipts.length > 0);
    assert.deepEqual(receipts.at(-1).payload.readBy, []);
    const now = new Date();
    await User.updateOne({ _id: bob._id }, { $set: { activeStatus: { isActive: true, presetKey: "at_seen", label: "At seen", startedAt: new Date(now - 31 * 60000) }, "presenceState.lastActivityAt": new Date(now - 31 * 60000) } });
    await pauseIdleAtSeen(now);
    assert.equal((await User.findById(bob._id)).activeStatus.isActive, false);
    assert.equal(ownPresence(await touchPresence(bob._id, { foreground: true, interaction: true }, now)).atSeenActive, true);
    await User.updateOne({ _id: bob._id }, { $set: { "activeStatus.isActive": false, "presenceState.pausedAt": new Date(now - 4 * 3600000) } });
    const late = await touchPresence(bob._id, { foreground: true, interaction: true }, now);
    assert.equal(ownPresence(late).offerAtSeen, true);
    assert.equal(late.activeStatus.isActive, false);
    const enabledOffer = await request(bob, "/presence/offer", { enable: true });
    assert.equal(enabledOffer.status, 200);
    assert.equal(enabledOffer.body.data.atSeenActive, true);
    // Force a manual status change between reading the old state and claiming the transition.
    const originalUpdate = User.findOneAndUpdate;
    let raced = false;
    const mocked = t.mock.method(User, "findOneAndUpdate", function (...args) {
      return { select() { return this; }, lean: async () => {
        if (!raced) { raced = true; await User.updateOne({ _id: bob._id }, { $set: { activeStatus: { isActive: true, label: "Working", presetKey: "working", startedAt: new Date() }, ...manualPresenceReset() }, $inc: { "presenceState.revision": 1 } }); }
        return originalUpdate.apply(User, args).select("activeStatus +presenceState").lean();
      } };
    });
    await touchPresence(bob._id, { foreground: true, interaction: true }); mocked.mock.restore();
    assert.equal((await User.findById(bob._id)).activeStatus.label, "Working");
    assert.equal((await request(bob, "/presence/offer", { enable: true })).body.data.activeStatus.label, "Working", "An old offer cannot overwrite a manual status");
    const story = await Story.collection.insertOne({ creator: alice._id, expiresAt: new Date(Date.now() + 3600000), image: { url: "/test.jpg" } });
    assert.equal((await request(bob, `/insights/${story.insertedId}`)).status, 403);
    assert.equal((await request(alice, `/insights/${story.insertedId}`)).status, 200);
    const account = await request(alice, "/me");
    assert.doesNotMatch(JSON.stringify(account.body), /lastSeenAt|lastActiveAt|presenceState|foregroundAt/);
    assert.doesNotMatch(JSON.stringify(captured), /lastSeenAt|lastActiveAt|foregroundAt/);
  } finally {
    sockets.forEach(socket => socket.disconnect());
    if (io) await new Promise(resolve => io.close(resolve));
    else if (server) await new Promise(resolve => server.close(resolve));
    await mongoose.disconnect(); await database.stop();
  }
});
