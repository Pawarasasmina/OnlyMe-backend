import test from "node:test";
import assert from "node:assert/strict";
import mongoose from "mongoose";
import { MongoMemoryServer } from "mongodb-memory-server";
import User from "../models/User.js";
import Gift from "../models/Gift.js";
import GiftPreference from "../models/GiftPreference.js";
import PlatformSetting from "../models/PlatformSetting.js";
import PayoutBankApplication from "../models/PayoutBankApplication.js";
import IdentityVerification from "../models/IdentityVerification.js";
import CreatorVerification from "../models/CreatorVerification.js";
import { monetizationSummary, completeMonetizationEligibility, requireMonetization, MONETIZATION_POLICY_KEY } from "./monetizationService.js";
import { creditWallet } from "./walletLedgerService.js";
test("monetization uses admin countries, immutable birthdays, live catalog and real verification", { skip: process.env.MONETIZATION_INTEGRATION !== "1", timeout: 180000 }, async () => {
  const server = await MongoMemoryServer.create();
  try {
    await mongoose.connect(server.getUri());
    const user = await User.create({ name: "Creator", username: "moncreator", email: "mon@example.com", password: "Password123", creatorApprovalStatus: "approved", profileAccountType: "creator" });
    let summary = await monetizationSummary(user);
    assert.equal(summary.enabled, false);
    await assert.rejects(requireMonetization(user._id, "gifts"), error => error.code === "MONETIZATION_NOT_ELIGIBLE");
    assert.deepEqual(summary.policy.supportedCountries, []);
    await PlatformSetting.create({ key: MONETIZATION_POLICY_KEY, value: { enabled: true, supportedCountries: ["Sri Lanka"], termsVersion: "test-v1" } });
    await assert.rejects(completeMonetizationEligibility(user, { dateOfBirth: "2020-01-01", country: "Sri Lanka", acceptTerms: true, termsVersion: "test-v1" }), /18/);
    await assert.rejects(completeMonetizationEligibility(user, { dateOfBirth: "1990-01-01", country: "Other", acceptTerms: true, termsVersion: "test-v1" }), /country/);
    await assert.rejects(completeMonetizationEligibility(user, { dateOfBirth: "1990-01-01", country: "Sri Lanka", acceptTerms: false, termsVersion: "test-v1" }), /Terms/);
    summary = await completeMonetizationEligibility(user, { dateOfBirth: "1990-01-01", country: "Sri Lanka", acceptTerms: true, termsVersion: "test-v1" });
    assert.equal(summary.enabled, true);
    assert.equal(summary.tools.gifts, false);
    const giftId = new mongoose.Types.ObjectId();
    await Gift.collection.insertOne({ _id: giftId, isActive: true, stars: 37, name: "Admin gift", image: { url: "test" } });
    let current = await User.findById(user._id);
    summary = await monetizationSummary(current);
    assert.equal(summary.tools.gifts, true);
    assert.equal((await requireMonetization(user._id, "gifts")).enabled, true);
    assert.equal(summary.tools.world, true);
    assert.equal(summary.verified, false);
    await completeMonetizationEligibility(current, { dateOfBirth: "2000-01-01", country: "Sri Lanka", acceptTerms: true, termsVersion: "test-v1" });
    assert.equal((await User.findById(user._id)).monetization.dateOfBirth.toISOString().slice(0, 10), "1990-01-01");
    await GiftPreference.create({ user: user._id, enabledGifts: [] });
    assert.equal((await monetizationSummary(current)).tools.gifts, false);
    await IdentityVerification.create({ user: user._id, status: "verified", payoutsEnabled: true, bankLast4: "1234" });
    assert.equal((await monetizationSummary(current)).payoutsReady, false);
    await CreatorVerification.collection.insertOne({ creator: user._id, status: "APPROVED", dateOfBirth: new Date("1991-01-01"), country: "Sri Lanka" });
    assert.equal((await monetizationSummary(current)).dateOfBirth, "1991-01-01");
    await PayoutBankApplication.collection.insertOne({ user: user._id, status: "APPROVED" });
    assert.equal((await monetizationSummary(current)).payoutsReady, true);
    await User.updateOne({ _id: user._id }, { $set: { profileAccountType: "personal" } });
    current = await User.findById(user._id);
    assert.equal((await monetizationSummary(current)).tools.world, false);
    assert.equal((await monetizationSummary(current)).tools.paidSeens, true);
    await PlatformSetting.updateOne({ key: MONETIZATION_POLICY_KEY }, { $set: { "value.enabled": false } });
    assert.equal((await monetizationSummary(current)).enabled, false);
    await assert.rejects(creditWallet({ user: user._id, entryType: "CHAT_GIFT_EARNING", entryRole: "CREATOR_EARNING", amount: 37 }), error => error.code === "MONETIZATION_NOT_ELIGIBLE");
    await PlatformSetting.updateOne({ key: MONETIZATION_POLICY_KEY }, { $set: { "value.enabled": true, "value.supportedCountries": [] } });
    await PayoutBankApplication.updateOne({ user: user._id }, { $set: { status: "PENDING_REVIEW", country: "AE" } });
    const waitingForAdmin = await completeMonetizationEligibility(current, { country: "UAE", acceptTerms: true, termsVersion: "test-v1" });
    assert.equal(waitingForAdmin.eligibility.terms, true);
    assert.equal(waitingForAdmin.eligibility.country, false);
    assert.equal(waitingForAdmin.enabled, false, "Entering a country cannot approve it");
    await PayoutBankApplication.updateOne({ user: user._id }, { $set: { status: "APPROVED" } });
    current = await User.findById(user._id);
    const approvedCountry = await monetizationSummary(current);
    assert.equal(approvedCountry.eligibility.country, true);
    assert.equal(approvedCountry.enabled, true);
    await PlatformSetting.updateOne({ key: MONETIZATION_POLICY_KEY }, { $set: { "value.supportedCountries": ["Sri Lanka"] } });
    assert.equal((await monetizationSummary(current)).eligibility.country, false, "An explicit admin whitelist is still enforced");
  } finally { await mongoose.disconnect(); await server.stop(); }
});
