import test from "node:test";
import assert from "node:assert/strict";
import mongoose from "mongoose";
import { MongoMemoryServer } from "mongodb-memory-server";
import User from "../models/User.js";
import Wallet from "../models/Wallet.js";
import PremiumMembership from "../models/PremiumMembership.js";
import Publication from "../models/Publication.js";
import { login } from "../controllers/authController.js";
import { accountOwnershipSummary, changeAccountOwnership } from "./accountOwnershipService.js";
import { processDueAccountDeletions } from "./accountDeletionService.js";
import { canAccessPublicationAudience, seenVisibilityFilter } from "./publicationAccessService.js";
import { protect } from "../middleware/authMiddleware.js";
import { issueAuthTokens } from "./tokenService.js";

test("ownership lifecycle preserves balances, revokes sessions, restores login and expires deletion", { skip: process.env.OWNERSHIP_INTEGRATION !== "1", timeout: 180000 }, async () => {
  const server = await MongoMemoryServer.create();
  try {
    await mongoose.connect(server.getUri());
    const user = await User.create({ name: "Owner", username: "owner", email: "owner@example.com", password: "Password123" });
    const viewer = await User.create({ name: "Member", username: "member", email: "member@example.com", password: "Password123" });
    await Wallet.create({ user: user._id, balance: 10772, earnedBalance: 10772 });
    const pubId = new mongoose.Types.ObjectId();
    await PremiumMembership.create({ user: viewer._id, creator: user._id, premiumPublication: pubId, currentPeriodStart: new Date(), currentPeriodEnd: new Date(Date.now() + 86400000), starsPerPeriod: 100, latestLedgerEntry: new mongoose.Types.ObjectId(), idempotencyKey: "test" });
    const summary = await accountOwnershipSummary(user);
    assert.equal(summary.unwithdrawnUsd, 1077.2);
    await assert.rejects(changeAccountOwnership(user, "delete", false), error => error.code === "UNWITHDRAWN_EARNINGS");
    const token = issueAuthTokens(user).accessToken;
    const inactive = await changeAccountOwnership(user, "deactivate");
    assert.equal(inactive.status, "deactivated");
    assert.equal((await Wallet.findOne({ user: user._id })).earnedBalance, 10772);
    const membership = await PremiumMembership.findOne({ creator: user._id });
    assert.equal(membership.cancelAtPeriodEnd, true);
    assert.equal(await canAccessPublicationAudience({ creator: user._id, kind: "SEEN" }, viewer), false);
    assert.equal(await canAccessPublicationAudience({ creator: user._id, kind: "PREMIUM_WORLD" }, viewer), true);
    assert.ok((await seenVisibilityFilter(viewer)).$and);
    let failure;
    await protect({ headers: { authorization: `Bearer ${token}` } }, {}, err => { failure = err; });
    assert.equal(failure.statusCode, 401);
    const response = { cookie() { return this; }, status() { return this; }, json(value) { this.body = value; return this; } };
    failure = null;
    await login({ body: { email: user.email, password: "Password123" }, headers: {}, get: () => "" }, response, err => { failure = err; });
    assert.ifError(failure);
    assert.equal(response.body.data.user.status, "active");
    let current = await User.findById(user._id);
    await changeAccountOwnership(current, "delete", true);
    assert.equal((await processDueAccountDeletions()).processed, 0);
    await login({ body: { email: user.email, password: "Password123" }, headers: {}, get: () => "" }, response, err => { throw err; });
    assert.equal((await User.findById(user._id)).deletionScheduledAt, null);
    current = await User.findById(user._id);
    await Publication.collection.insertOne({ _id: pubId, creator: user._id, kind: "SEEN", status: "PUBLISHED" });
    const past = new Date(Date.now() - 31 * 86400000);
    await changeAccountOwnership(current, "delete", true, past);
    assert.equal((await processDueAccountDeletions()).processed, 1);
    const deleted = await User.findById(user._id);
    assert.equal(deleted.status, "deleted");
    assert.equal(deleted.name, "Deleted account");
    assert.equal(await Publication.countDocuments({ creator: user._id }), 0);
    assert.equal((await processDueAccountDeletions()).processed, 0);
  } finally { await mongoose.disconnect(); await server.stop(); }
});
